"""
Publishing the dashboard to a PRIVATE GitHub repository that Streamlit Community Cloud deploys from (viewers limited to named people there). The repository holds a small copy of the app plus
the exported data; every publish commits the new data, and the deployed app picks it up. Refuses to push unless the remote is a private repository.
"""
import json
import shutil
import subprocess
from pathlib import Path

import pandas as pd

APP_FILES = {'dashboard_props/app.py': 'dashboard_props/app.py', 'dashboard_props/logic.py': 'dashboard_props/logic.py', 'dashboard/requirements.txt': 'requirements.txt',
             'core/__init__.py': 'core/__init__.py', 'core/live_feed.py': 'core/live_feed.py', 'core/live_feed_overrides.csv': 'core/live_feed_overrides.csv'}   # the live panel's feed
DATA_DIRS = {'live': 'data/props_dashboard_live', 'backtest': 'data/props_dashboard'}
VOLATILE = {'PUBLISHED.json', 'data/props_dashboard_live/meta.json', 'data/props_dashboard_live/checks.csv', 'data/props_dashboard_live/pipeline_health.csv',
            'data/props_dashboard_live/slot_log.csv'}        # change on every refresh without carrying news
IDENT = ['-c', 'user.name=NBA props publisher', '-c', 'user.email=noreply@users.noreply.github.com']
README = ("# NBA props dashboard (private)\n\nGenerated by `scripts/publish_props_dashboard.py` in the model repository; do not edit by hand. "
          "`dashboard_props/app.py` is the Streamlit entry point; `data/` holds the exported tables the app reads.\n")


def git(repo, *args, check=True):
    return subprocess.run(['git', *args], cwd=repo, capture_output=True, text=True, check=check)


def is_private(remote):
    """True only when GitHub says the repository is private (the check needs the gh CLI and access to the repo)."""
    slug = remote.split('github.com')[-1].lstrip(':/').removesuffix('.git')
    r = subprocess.run(['gh', 'repo', 'view', slug, '--json', 'isPrivate'], capture_output=True, text=True)
    return r.returncode == 0 and json.loads(r.stdout).get('isPrivate') is True


def build_bundle(dest, src_root='.', live_dir=None, backtest_dir=None, now=None):
    """Writes the app, its requirements and the data into `dest` (an existing checkout of the private repository). Returns the files written."""
    dest, src_root = Path(dest), Path(src_root)
    written = []
    for src, dst in APP_FILES.items():
        (dest / dst).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src_root / src, dest / dst)
        written.append(dst)
    for name, default in DATA_DIRS.items():
        src = Path((live_dir if name == 'live' else backtest_dir) or src_root / default)
        if not (src / 'bets.csv').exists():
            continue
        target = dest / default
        target.mkdir(parents=True, exist_ok=True)
        for f in src.iterdir():
            if f.is_file() and f.suffix in ('.csv', '.json'):
                if not (target / f.name).exists() or (target / f.name).read_bytes() != f.read_bytes():       # unchanged files are not rewritten (the backtest export is 38 MB)
                    shutil.copyfile(f, target / f.name)
                written.append(f'{default}/{f.name}')
    (dest / '.streamlit').mkdir(exist_ok=True)
    (dest / '.streamlit' / 'config.toml').write_text('[server]\nheadless = true\n\n[browser]\ngatherUsageStats = false\n', encoding='utf-8')
    (dest / 'README.md').write_text(README, encoding='utf-8')
    stamp = (now or pd.Timestamp.now(tz='UTC')).strftime('%Y-%m-%dT%H:%M:%SZ')
    (dest / 'PUBLISHED.json').write_text(json.dumps({'published_utc': stamp}, indent=1), encoding='utf-8')
    return written


def publish(remote, clone_dir, src_root='.', require_private=True, live_dir=None, backtest_dir=None, now=None, branch='main', min_interval_min=None):
    """
    Clone (once), refresh the bundle, commit if anything but the timestamp changed, push. Returns 'pushed', 'unchanged' or raises. With `min_interval_min`, a refresh whose only changes are
    the volatile files (build time, health tables) is not pushed unless that many minutes have passed since the last push, so a 10-minute schedule does not flood the repository with commits.
    """
    if require_private and not is_private(remote):
        raise RuntimeError(f'refusing to publish: {remote} is not confirmed to be a private repository')
    clone_dir = Path(clone_dir)
    if not (clone_dir / '.git').exists():
        clone_dir.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(['git', 'clone', '-q', remote, str(clone_dir)], check=True)
    else:
        git(clone_dir, 'pull', '-q', '--rebase', check=False)
    build_bundle(clone_dir, src_root, live_dir, backtest_dir, now)
    git(clone_dir, 'add', '-A')
    changed = [l[3:] for l in git(clone_dir, 'status', '--porcelain').stdout.splitlines()]
    if not changed or changed == ['PUBLISHED.json']:                      # nothing new but the timestamp: do not create a commit for it
        git(clone_dir, 'reset', '-q', 'HEAD', '--', 'PUBLISHED.json', check=False)
        git(clone_dir, 'checkout', '--', 'PUBLISHED.json', check=False)
        return 'unchanged'
    if min_interval_min is not None and set(changed) <= VOLATILE:
        last = pd.Timestamp(json.loads(git(clone_dir, 'show', 'HEAD:PUBLISHED.json').stdout)['published_utc'])
        if ((now or pd.Timestamp.now(tz='UTC')) - last) < pd.Timedelta(minutes=min_interval_min):
            git(clone_dir, 'reset', '-q', '--hard', 'HEAD')
            return 'unchanged'
    stamp = json.loads((clone_dir / 'PUBLISHED.json').read_text())['published_utc']
    git(clone_dir, *IDENT, 'commit', '-q', '-m', f'Data through {stamp}')
    git(clone_dir, 'push', '-q', 'origin', f'HEAD:{branch}')
    return 'pushed'
